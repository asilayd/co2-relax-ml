"""Физика CO2: константы мод и сродство процессов.

Молекула CO2 линейна и имеет три колебательные моды. Моды nu1 и nu2 связаны
резонансом Ферми (nu1 ~ 2*nu2) и объединяются в комбинированную моду 12
со счётом квантов i12 = 2*i1 + i2; мода nu3 описывается отдельно.
"""
from __future__ import annotations

import numpy as np

# Волновые числа мод, см^-1
NU_1, NU_2, NU_3 = 1333.0, 667.0, 2349.0

# 1 см^-1 в кельвинах: h*c/k
CM_TO_K = 1.4387769

# Характеристические температуры мод, K
THETA_1 = 1918.0
THETA_2 = 960.0
THETA_3 = 3380.0

# Энергетические дефекты VV-процессов, K.
# Оба канала переносят квант nu3 в три единицы моды 12, поэтому дефекты
# практически совпадают (резонанс Ферми): 500 K против 502 K.
DELTA_VV23 = THETA_3 - 3 * THETA_2
DELTA_VV123 = THETA_3 - THETA_1 - THETA_2


def affinity_vv23(T, T12, T3):
    """Сродство процесса VV23: nu3 <-> 3*nu2.

    phi > 0 — кванты текут из моды 3 в моду 12 (R_VV23_12 > 0),
    phi < 0 — наоборот, phi = 0 — нулевая поверхность.
    Тождественно ноль при T = T12 = T3, поскольку DELTA = THETA_3 - 3*THETA_2.
    """
    return 3 * THETA_2 / T12 + DELTA_VV23 / T - THETA_3 / T3


def affinity_vv123(T, T12, T3):
    """Сродство процесса VV123: nu3 <-> nu1 + nu2.

    Отличается от VV23 только дефектом (502 K против 500 K); по данным
    нулевые поверхности каналов совпадают в пределах погрешности сетки.
    """
    return (THETA_1 + THETA_2) / T12 + DELTA_VV123 / T - THETA_3 / T3


def affinity_vt2(T, T12, T3=None):
    """Сродство процесса VT2: квант nu2 -> поступательная энергия.

    Дефекта нет — квант уходит в тепло целиком. T3 принимается для
    единообразия сигнатуры и не используется.
    """
    return THETA_2 / T12 - THETA_2 / T


AFFINITY = {
    "R_VT2_12": affinity_vt2,
    "R_VV23_12": affinity_vv23,
    "R_VV123_12": affinity_vv123,
}


def factor(phi):
    """Множитель детального баланса 1 - exp(-phi).

    expm1 вместо 1 - exp: при малых |phi| прямая формула теряет значащие
    цифры, а малые phi — это окрестность нулевой поверхности, самая
    чувствительная область.
    """
    return -np.expm1(-np.asarray(phi, dtype=float))


# Те же формулы для torch-тензоров: нужны, когда производные по температурам
# считаются автоматическим дифференцированием (якобиан для неявных схем).
AFFINITY_TORCH = {
    "R_VT2_12": lambda T, T12, T3: THETA_2 / T12 - THETA_2 / T,
    "R_VV23_12": lambda T, T12, T3: 3 * THETA_2 / T12 + DELTA_VV23 / T - THETA_3 / T3,
    "R_VV123_12": lambda T, T12, T3: (THETA_1 + THETA_2) / T12 + DELTA_VV123 / T - THETA_3 / T3,
}